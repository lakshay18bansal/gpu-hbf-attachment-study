#!/usr/bin/env python3
"""Build the comparison report from run folders (each with run_meta.json + metrics.json).

usage: report.py <results dir> [<results dir> ...] [-o results/REPORT.md] [--csv results/runs.csv]
                 [--plots results/plots]

Sections:
  1. every run: cycles, time, slowdown vs C1 on the same workload, per-tier bandwidth, HBF counters
  2. Qwen3-1.7B time per output token (TPOT) and tokens/s:
       TPOT = (prologue + 28 x layer13 + tail) cycles / core clock.
     Prologue and tail (incl. the 622 MB lm_head GEMV) are simulated at tR 15 us; for other tR their
     cycles are estimated by scaling with the layer's tR ratio (marked 'est.').
  3. layer-13 breakdown by kernel class (GEMV attention projections, GEMV MLP, norms, attention, other)
  4. ratios for the literature comparison (C3 vs C4, prefetch effect, slowdown vs HBM)
"""
import argparse
import csv
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

ST = Path(__file__).resolve().parents[1]
LAYERS = 28
CFG_ORDER = ['C1_hbm_only', 'C2_hbf_dram', 'C3_iso_stack', 'C3_iso_shoreline', 'C4_behind_hbm',
             'C2_legacy_paper']


def load_runs(dirs):
    runs = []
    for d in dirs:
        for mj in sorted(Path(d).glob('*/metrics.json')):
            r = mj.parent
            meta_p = r / 'run_meta.json'
            if not meta_p.exists():
                continue
            m = json.loads(mj.read_text())
            meta = json.loads(meta_p.read_text())
            runs.append({'dir': r, 'name': r.name, 'm': m, 'meta': meta})
    return runs


def wl_key(meta):
    return meta['workload']


def variant(meta, name):
    v = f"tR{meta['tR_us']:g} pf-{meta['prefetch']}" if meta['hbf'] else '-'
    hop = re.search(r'__hop(\d+)$', name)
    if hop:
        v += f" hop+{hop.group(1)}ns"
    return v


def cfg_rank(c):
    return CFG_ORDER.index(c) if c in CFG_ORDER else len(CFG_ORDER)


def fmt(x, nd=1, pct=False):
    if x is None:
        return '-'
    if isinstance(x, float):
        s = f'{x:,.{nd}f}'
    else:
        s = f'{x:,}'
    return s + ('%' if pct else '')


def kernel_classes(layer_list, hints):
    """Class per launch position of list_layer13.g from kernel names + weight pages in the hints."""
    files = [x for x in layer_list.read_text().split() if x.startswith('kernel')]
    pages = {}
    if hints.exists():
        for line in hints.read_text().splitlines():
            if line and line[0] != '#':
                t = line.split()
                pages[int(t[0])] = int(t[1])
    out = []
    for i, f in enumerate(files, 1):
        with __import__('lzma').open(layer_list.parent / f, 'rt') as fh:
            name = fh.readline().split('=', 1)[1].strip()
        wb = pages.get(i, 0) * 4096
        n = name.lower()
        if 'gemv' in n and wb:
            c = 'GEMV attn proj (q,k,v,o)' if wb <= 8 << 20 else 'GEMV MLP (gate,up,down)'
        elif any(k in n for k in ('reduce_kernel', 'rsqrt', 'pow_tensor', 'meanops')) or (wb and wb < 1 << 20):
            c = 'RMSNorm'
        elif any(k in n for k in ('softmax', 'bmm', 'gemm', 'gemv', 'cat')):
            c = 'attention (QK^T, softmax, AV, KV cat)'
        else:
            c = 'elementwise / other'
        out.append({'pos': i, 'file': f, 'name': name[:60], 'weight_bytes': wb, 'cls': c})
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('dirs', nargs='+')
    ap.add_argument('-o', '--out', default=str(ST / 'results' / 'REPORT.md'))
    ap.add_argument('--csv', default=str(ST / 'results' / 'runs.csv'))
    ap.add_argument('--plots', default=str(ST / 'results' / 'plots'))
    a = ap.parse_args()
    runs = load_runs(a.dirs)
    if not runs:
        sys.exit('no runs found')
    L = []
    L.append('# HBM / HBF memory-organization study: results\n')
    L.append('Generated by `tools/report.py` from ' + ', '.join(f'`{Path(d).name}`' for d in a.dirs) +
             '. GPU: 16-SM A100-profile slice (C2_legacy_paper: 8 SMs, as in the HBF-Sim paper) (`common/gpu/qwen3_slice.config`, 1410 MHz). '
             'Configurations: see `docs/02_design.md` and each folder README.\n')
    bad = [r for r in runs if not r['m'].get('ok')]
    if bad:
        L.append('**Failed / incomplete runs:** ' + ', '.join(r['name'] for r in bad) + '\n')
    runs = [r for r in runs if r['m'].get('ok')]

    # C1 reference per workload
    ref = {}
    for r in runs:
        if r['meta']['config'] == 'C1_hbm_only':
            ref[wl_key(r['meta'])] = r['m']['cycles']

    # ---- 1. all runs
    rows = []
    for r in runs:
        m, meta = r['m'], r['meta']
        h = m.get('hbf') or {}
        ram = m.get('ramulator') or {}
        c1 = ref.get(wl_key(meta))
        rows.append({
            'workload': wl_key(meta), 'config': meta['config'], 'variant': variant(meta, r['name']),
            'tR_us': meta['tR_us'] if meta['hbf'] else '', 'prefetch': meta['prefetch'] if meta['hbf'] else '',
            'cycles': m['cycles'], 'time_us': round(m['time_us'], 2),
            'slowdown_vs_C1': round(m['cycles'] / c1, 4) if c1 else '',
            'hbm_gbps': round(ram.get('gbps', 0), 1) if ram else '',
            'hbm_pct_peak': round(ram.get('pct_of_peak', 0), 1) if ram else '',
            'hbf_read_gbps': round(h.get('read_gbps', 0), 1) if h else '',
            'hbf_pct_link': round(h.get('pct_of_link', 0), 1) if h.get('pct_of_link') is not None else '',
            'array_amp': round(h['array_amplification'], 3) if h.get('array_amplification') else '',
            'service_amp': round(h['service_amplification'], 2) if h.get('service_amplification') else '',
            'mshr_merge': round(h['mshr_merge_rate'], 3) if h.get('mshr_merge_rate') is not None else '',
            'lhb_hit': round(h['lhb_request_hit_rate'], 4) if h.get('lhb_request_hit_rate') is not None else '',
            'pf_useful': h.get('prefetch_useful', ''), 'pf_wasted': h.get('prefetch_wasted', ''),
            'e2e_avg_cyc': h.get('e2e_latency_avg', ''), 'e2e_p95_cyc': h.get('e2e_latency_p95', ''),
            'phy_hbf_stall_ticks': h.get('phy_hbf_stall_ticks', ''), 'phy_hbm_stall_ticks': h.get('phy_hbm_stall_ticks', ''),
            'host_s': m.get('host_seconds', ''), 'run': r['name'],
        })
    rows.sort(key=lambda x: (x['workload'], cfg_rank(x['config']), str(x['tR_us']), x['prefetch'], x['variant']))
    Path(a.csv).parent.mkdir(parents=True, exist_ok=True)
    with open(a.csv, 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    L.append('## 1. All runs\n')
    L.append('Slowdown is cycles / cycles of C1 on the same workload. HBM GB/s = Ramulator 32 B transactions '
             '(reads + writes) / time; HBF GB/s = GPU-requested HBF read bytes / time; % link = of the slice\'s '
             'HBF link bandwidth. Array amp. = NAND array reads x 4 KiB / requested bytes (1.0 = every byte read '
             'once); LHB hit = fraction of HBF requests served from the prefetch buffer. Latency = HBF request '
             'end to end (L2 exit to reply), core cycles (0.709 ns each).\n')
    for wl in sorted({x['workload'] for x in rows}):
        L.append(f'### {wl}\n')
        L.append('| Config | Variant | Cycles | Time (us) | vs C1 | HBM GB/s (% peak) | HBF GB/s (% link) | '
                 'Array amp. | MSHR merge | LHB hit | HBF lat avg / p95 | Host s |')
        L.append('|---|---|---|---|---|---|---|---|---|---|---|---|')
        for x in rows:
            if x['workload'] != wl:
                continue
            hbm = f"{x['hbm_gbps']} ({x['hbm_pct_peak']}%)" if x['hbm_gbps'] != '' else '-'
            hbf = f"{x['hbf_read_gbps']} ({x['hbf_pct_link']}%)" if x['hbf_read_gbps'] != '' else '-'
            lat = (f"{fmt(x['e2e_avg_cyc'], 0)} / {fmt(x['e2e_p95_cyc'], 0)}" if x['e2e_avg_cyc'] != '' else '-')
            L.append(f"| {x['config']} | {x['variant']} | {x['cycles']:,} | {x['time_us']:,} | "
                     f"{x['slowdown_vs_C1'] or '-'} | {hbm} | {hbf} | {x['array_amp'] or '-'} | "
                     f"{x['mshr_merge'] or '-'} | {x['lhb_hit'] if x['lhb_hit'] != '' else '-'} | {lat} | {x['host_s']} |")
        L.append('')

    # ---- 2. TPOT
    by = defaultdict(dict)  # (config, tR, pf, variant-suffix) -> workload -> cycles
    for x in rows:
        if 'hop' in x['variant']:
            continue
        k = (x['config'], x['tR_us'], x['prefetch'])
        by[k][x['workload']] = x['cycles']
    core = runs[0]['meta'].get('core_mhz', 1410.0)
    tp = []
    for (c, tr, pf), d in by.items():
        if 'qwen3_layer13' not in d:
            continue
        lay = d['qwen3_layer13']
        est = False
        parts = {}
        for part in ('qwen3_prologue', 'qwen3_tail'):
            if part in d:
                parts[part] = d[part]
                continue
            # Not simulated for this (tR, prefetch): scale the same config's tR-15 run of this
            # part (same prefetch setting if available, else prefetch on) by the layer ratio.
            for bk in ((c, 15.0, pf), (c, 15.0, 'on')):
                b = by.get(bk)
                if b and part in b and 'qwen3_layer13' in b:
                    parts[part] = b[part] * lay / b['qwen3_layer13']
                    est = True
                    break
        if len(parts) < 2:
            continue
        pro, tail = parts['qwen3_prologue'], parts['qwen3_tail']
        tot = pro + LAYERS * lay + tail
        tp.append({'config': c, 'tR': tr, 'pf': pf, 'cycles': tot, 'tpot_ms': tot / core / 1e3, 'est': est})
    if tp:
        c1 = next((t for t in tp if t['config'] == 'C1_hbm_only'), None)
        tp.sort(key=lambda t: (cfg_rank(t['config']), str(t['tR']), t['pf']))
        L.append('## 2. Qwen3-1.7B decode: time per output token (batch 1)\n')
        L.append('TPOT = (prologue + 28 x layer 13 + tail) / 1410 MHz on the 16-SM slice. "est." = prologue/tail '
                 'scaled from the tR 15 us runs by the layer\'s cycle ratio.\n')
        L.append('| Config | tR (us) | Prefetch | Cycles / token | TPOT (ms) | Tokens/s | vs C1 |')
        L.append('|---|---|---|---|---|---|---|')
        for t in tp:
            vs = f"{t['cycles'] / c1['cycles']:.3f}x" if c1 else '-'
            L.append(f"| {t['config']} | {t['tR'] or '-'} | {t['pf'] or '-'} | {t['cycles']:,.0f}{' (est.)' if t['est'] else ''} | "
                     f"{t['tpot_ms']:.3f} | {1e3 / t['tpot_ms']:.1f} | {vs} |")
        L.append('')
        (Path(a.csv).parent / 'tpot.json').write_text(json.dumps(tp, indent=1))

    # ---- 2b. full model from all 28 simulated layers (suite 'fullmodel')
    full = defaultdict(dict)
    for x in rows:
        m_ = re.fullmatch(r'qwen3_layer:(\d+)', x['workload'])
        if m_ and 'hop' not in x['variant']:
            full[(x['config'], x['tR_us'], x['prefetch'])][int(m_.group(1))] = x['cycles']
    done = {k: v for k, v in full.items() if len(v) == LAYERS}
    if done:
        c1f = next((sum(v.values()) for k, v in done.items() if k[0] == 'C1_hbm_only'), None)
        L.append('## 2b. Qwen3-1.7B decode with all 28 layers simulated (suite fullmodel)\n')
        L.append('TPOT = (prologue + sum of the 28 simulated layers + tail) / 1410 MHz. "x28 error" = '
                 '(28 x layer 13) / (sum of 28 layers) - 1, i.e. the error of the one-layer extrapolation.\n')
        L.append('| Config | tR (us) | Prefetch | Layer cycles min / max | Cycles / token | TPOT (ms) | vs C1 | x28 error |')
        L.append('|---|---|---|---|---|---|---|---|')
        for (c, tr, pf), v in sorted(done.items(), key=lambda kv: (cfg_rank(kv[0][0]), str(kv[0][1]), kv[0][2])):
            d = by.get((c, tr, pf), {})
            base = by.get((c, 15.0, 'on')) or by.get((c, 15.0, pf)) or {}
            pro = d.get('qwen3_prologue', base.get('qwen3_prologue'))
            tail = d.get('qwen3_tail', base.get('qwen3_tail'))
            if pro is None or tail is None:
                continue
            s_ = sum(v.values())
            tot = pro + s_ + tail
            err = (LAYERS * d['qwen3_layer13'] / s_ - 1) * 100 if 'qwen3_layer13' in d else None
            vs = f"{tot / (c1f + by[('C1_hbm_only', '', '')]['qwen3_prologue'] + by[('C1_hbm_only', '', '')]['qwen3_tail']):.3f}x" \
                if c1f and ('C1_hbm_only', '', '') in by else '-'
            L.append(f"| {c} | {tr or '-'} | {pf or '-'} | {min(v.values()):,} / {max(v.values()):,} | {tot:,} | "
                     f"{tot / core / 1e3:.3f} | {vs} | {f'{err:+.2f}%' if err is not None else '-'} |")
        L.append('')

    # ---- 3. kernel classes
    layer_list = ST / 'workloads/qwen3_1p7b/trace/list_layer13.g'
    hints = ST / 'workloads/qwen3_1p7b/trace/hints/list_layer13.hints'
    lay_runs = [r for r in runs if wl_key(r['meta']) == 'qwen3_layer13' and 'hop' not in r['name']]
    if lay_runs and layer_list.exists():
        classes = kernel_classes(layer_list, hints)
        cls_names = list(dict.fromkeys(c['cls'] for c in classes))
        L.append('## 3. Layer 13 by kernel class (cycles, sum over the class\'s kernels incl. launch latency)\n')
        wb = defaultdict(int)
        for c in classes:
            wb[c['cls']] += c['weight_bytes']
        L.append('Weight bytes per class: ' + ', '.join(f'{k}: {v / 2**20:.1f} MiB' for k, v in wb.items()) + '\n')
        L.append('| Config | Variant | ' + ' | '.join(cls_names) + ' |')
        L.append('|---|---|' + '---|' * len(cls_names))
        lay_runs.sort(key=lambda r: (cfg_rank(r['meta']['config']), r['meta']['tR_us'], r['meta']['prefetch']))
        for r in lay_runs:
            ks = r['m']['kernels']
            if len(ks) != len(classes):
                continue
            agg = defaultdict(int)
            for k, c in zip(ks, classes):
                agg[c['cls']] += k['cycles']
            L.append(f"| {r['meta']['config']} | {variant(r['meta'], r['name'])} | " +
                     ' | '.join(f'{agg[c]:,}' for c in cls_names) + ' |')
        L.append('')
        with open(Path(a.csv).parent / 'kernels_layer13.csv', 'w', newline='') as f:
            w = csv.DictWriter(f, fieldnames=list(classes[0]))
            w.writeheader()
            w.writerows(classes)

    # ---- 4. ratios
    L.append('## 4. Ratios for the literature comparison\n')
    idx = {(x['workload'], x['config'], str(x['tR_us']), x['prefetch'], x['variant']): x for x in rows}

    def cyc(wl, c, tr, pf):
        for (w_, c_, t_, p_, v_), x in idx.items():
            if w_ == wl and c_ == c and t_ == str(tr) and p_ == pf and 'hop' not in v_:
                return x['cycles']
        return None
    L.append('Cycle ratios (>1 = the first config is slower).\n')
    L.append('| Workload | tR (us) | Cycle ratio | Value | Literature |')
    L.append('|---|---|---|---|---|')
    for wl in sorted({x['workload'] for x in rows}):
        for tr in sorted({x['tR_us'] for x in rows if x['workload'] == wl and x['tR_us'] != ''}):
            pairs = [
                ('C3-iso-stack / C4 (prefetch on)', cyc(wl, 'C4_behind_hbm', tr, 'on'), cyc(wl, 'C3_iso_stack', tr, 'on'),
                 'DASH: DirectOnly ~ RelayOnly (within ~3%) at equal links'),
                ('C3-iso-shoreline / C4 (prefetch on)', cyc(wl, 'C4_behind_hbm', tr, 'on'), cyc(wl, 'C3_iso_shoreline', tr, 'on'),
                 'FlashAccel: CSI (C4) 2.49x vs CLI (C3) 2.00x throughput/GPU -> C4 ~1.25x faster'),
                ('C3-iso-stack: prefetch off / on', cyc(wl, 'C3_iso_stack', tr, 'on'), cyc(wl, 'C3_iso_stack', tr, 'off'),
                 'FlashAccel: no prefetch -55% throughput'),
                ('C4 (pf on) / C1', cyc(wl, 'C1_hbm_only', '', ''), cyc(wl, 'C4_behind_hbm', tr, 'on'),
                 'FlashAccel full design within ~4% of HBM; TileLens 1.01x at tR 5 us'),
                ('C2 (pf on) / C1', cyc(wl, 'C1_hbm_only', '', ''), cyc(wl, 'C2_hbf_dram', tr, 'on'), '-'),
            ]
            for lab, den, num, lit in pairs:
                if den and num:
                    L.append(f'| {wl} | {tr} | {lab} | {num / den:.3f} | {lit} |')
    L.append('')
    Path(a.out).write_text('\n'.join(L) + '\n')
    print(f'wrote {a.out}, {a.csv} ({len(rows)} runs)')

    # ---- plots
    try:
        import matplotlib
        matplotlib.use('Agg')
        import matplotlib.pyplot as plt
    except ImportError:
        print('matplotlib not available: no plots (run with accel_sim_hbf/.venv/bin/python)')
        return
    if tp:
        pd = Path(a.plots)
        pd.mkdir(parents=True, exist_ok=True)
        fig, ax = plt.subplots(figsize=(7, 4.2))
        c1 = next((t for t in tp if t['config'] == 'C1_hbm_only'), None)
        for c in [x for x in CFG_ORDER if x not in ('C1_hbm_only', 'C2_legacy_paper')]:
            for pf, ls in (('off', '--'), ('on', '-')):
                pts = sorted((t['tR'], t['tpot_ms']) for t in tp if t['config'] == c and t['pf'] == pf and t['tR'] != '')
                if pts:
                    ax.plot([p[0] for p in pts], [p[1] for p in pts], ls, marker='o', label=f'{c} pf-{pf}')
        if c1:
            ax.axhline(c1['tpot_ms'], color='k', lw=1, label='C1 HBM only')
        ax.set_xlabel('NAND page read time tR (us)')
        ax.set_ylabel('Time per output token (ms)')
        ax.set_yscale('log')
        ax.legend(fontsize=7)
        ax.grid(alpha=.3)
        fig.tight_layout()
        fig.savefig(pd / 'tpot_vs_tR.png', dpi=150)
        print(f'wrote {pd / "tpot_vs_tR.png"}')


if __name__ == '__main__':
    main()
